	w = screen.getWidth()
	h = screen.getHeight()
	lw = 32
	lh = 32
	pw = w/lw
	ph = h/lh
	x = w/2-lw/2*pw
	y = 0*ph
	ia = 255
	ai = 3
	for k,v in pairs(Px) do
