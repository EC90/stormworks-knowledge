function calculateLampValue(value)
    -- ??value?0~1??
    if value < 0 then value = 0 end
    if value > 1 then value = 1 end

    -- ?????????(0~8)
    local lampCount = math.floor(value * 8 + 0.5)

    -- ??????:??lampCount?1,?????
    local bin = 0
    for i = 0, lampCount - 1 do
        bin = bin + 2^i
    end

    return bin
end
