function onTick()
inputX = input.getNumber(3)
inputY = input.getNumber(4)
isPressed = input.getBool(1)
C=input.getNumber(18)
AutoPon=input.getBool(3)
AutoPonP = isPressed and isPointInRectangle(inputX, inputY,76,59,30,10)
Home = isPressed and isPointInRectangle(inputX, inputY,37,56,23,7)
output.setBool(3, AutoPonP)
output.setBool(1, Home)
end
function isPointInRectangle(x, y, rectX, rectY, rectW, rectH)
	return x > rectX and y > rectY and x < rectX+rectW and y < rectY+rectH
end
