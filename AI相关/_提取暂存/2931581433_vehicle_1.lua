function onDraw()
	w = screen.getWidth()
	h = screen.getHeight()
	lw = 32
	lh = 32
	pw = w/lw
	ph = h/lh
	x = w/2-lw/2*pw
	y = 0*ph
	ia = TRANS
	ai = 2
	for k,v in pairs(Px) do
		if v == ai then a = 0 else a = ia end
		screen.setColor(CT[v*3-2],CT[v*3-1],CT[v*3], a)
		screen.drawRectF(x,y,pw,ph)
		x=x+pw
		if x>=w/2+lw/2*pw then y=y+ph x=0 end
	end
end
